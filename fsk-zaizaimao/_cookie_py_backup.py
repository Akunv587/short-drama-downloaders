"""Cookie management: cookies.txt + CDP extraction."""
from __future__ import annotations
import asyncio
import json
import os
import subprocess
import sys
import time
from pathlib import Path
from config import COOKIES_FILE
from core.utils.logger import get_logger

logger = get_logger("cookie")

COOKIE_TTL_SECONDS = 86400

CHROME_EXE_PATHS = [
    r"C:\Program Files\Google\Chrome\Application\chrome.exe",
    r"C:\Program Files (x86)\Google\Chrome\Application\chrome.exe",
    os.path.expandvars(r"%LOCALAPPDATA%\Google\Chrome\Application\chrome.exe"),
]

if sys.platform == "darwin":
    CHROME_EXE_PATHS = [
        "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
    ]
if sys.platform == "linux":
    CHROME_EXE_PATHS = [
        "google-chrome", "google-chrome-stable", "chromium", "chromium-browser",
    ]


def load_cookies() -> str:
    if COOKIES_FILE.exists():
        return COOKIES_FILE.read_text(encoding="utf-8").strip()
    return ""


def save_cookies(cookie_text: str):
    COOKIES_FILE.write_text(cookie_text, encoding="utf-8")


# ── CDP port detection ─────────────────────────────────

async def _find_chrome_debug_port() -> int | None:
    """Probe Chrome remote debugging ports (9222-9225)."""
    try:
        import aiohttp
        async with aiohttp.ClientSession() as session:
            for port in range(9222, 9226):
                try:
                    async with session.get(
                        f"http://127.0.0.1:{port}/json/version",
                        timeout=aiohttp.ClientTimeout(total=3),
                    ) as resp:
                        info = await resp.json()
                        if info.get("Browser"):
                            logger.info(f"Chrome debug port: {port} ({info.get('Browser')})")
                            return port
                except Exception:
                    continue
    except ImportError:
        logger.warning("aiohttp not installed, CDP unavailable")
        return None
    return None


# ── CDP cookie extraction ──────────────────────────────

async def _cdp_get_cookies(port: int, domains: list[str]) -> list[dict]:
    """Get cookies for specified domains via CDP Network.getCookies."""
    import aiohttp
    async with aiohttp.ClientSession() as session:
        # Get available targets
        async with session.get(
            f"http://127.0.0.1:{port}/json", timeout=aiohttp.ClientTimeout(total=5)
        ) as resp:
            targets = await resp.json()

        page_target = (
            next((t for t in targets if t.get("type") == "page" and "tiktok.com" in t.get("url", "")), None)
            or next((t for t in targets if t.get("type") == "page"), None)
            or next((t for t in targets if t.get("webSocketDebuggerUrl")), None)
        )

        if not page_target or not page_target.get("webSocketDebuggerUrl"):
            raise RuntimeError("No usable Chrome debug target found")

        ws_url = page_target["webSocketDebuggerUrl"]

    try:
        async with aiohttp.ClientSession() as session:
            async with session.ws_connect(
                ws_url, timeout=aiohttp.ClientTimeout(total=10), max_msg_size=4 * 1024 * 1024
            ) as ws:
                msg_id = 42
                await ws.send_json({
                    "id": msg_id,
                    "method": "Network.getCookies",
                    "params": {"urls": domains},
                })

                async for msg in ws:
                    if msg.type == aiohttp.WSMsgType.TEXT:
                        data = msg.json()
                        if data.get("id") == msg_id:
                            if data.get("error"):
                                raise RuntimeError(
                                    f"CDP error: {data['error'].get('message', 'unknown')}"
                                )
                            return data.get("result", {}).get("cookies", [])
                    elif msg.type in (aiohttp.WSMsgType.ERROR, aiohttp.WSMsgType.CLOSED):
                        break
    except asyncio.TimeoutError:
        raise RuntimeError("CDP WebSocket timeout (10s)")

    return []


def _cookies_to_netscape(cookies: list[dict]) -> str:
    """Convert CDP cookies to Netscape cookies.txt format."""
    lines = [
        "# Netscape HTTP Cookie File",
        "# Generated by zaizaicat CDP",
        "# https://curl.haxx.se/rfc/cookie_spec.html",
        "",
    ]
    for c in cookies:
        domain = c.get("domain", "")
        path = c.get("path", "/")
        secure = "TRUE" if c.get("secure") else "FALSE"
        expires = int(c["expires"]) if c.get("expires", 0) > 0 else 2147483647
        name = c.get("name", "")
        value = c.get("value", "")
        is_domain_cookie = domain.startswith(".")
        flag = "TRUE" if is_domain_cookie else "FALSE"
        lines.append("\t".join([
            domain, flag, path, secure, str(expires), name, value,
        ]))
    return "\n".join(lines) + "\n"


# ── Chrome launch ──────────────────────────────────────

async def _launch_chrome_with_debug() -> bool:
    chrome_exe = None
    for p in CHROME_EXE_PATHS:
        if os.path.exists(p):
            chrome_exe = p
            break

    if not chrome_exe:
        logger.warning("Chrome installation not found")
        return False

    temp_dir = os.path.join(os.environ.get("TEMP", "/tmp"), "chrome-debug-profile")
    try:
        if sys.platform == "win32":
            subprocess.Popen(
                [chrome_exe, "--remote-debugging-port=9222",
                 f"--user-data-dir={temp_dir}", "https://www.tiktok.com/"],
                stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                creationflags=subprocess.DETACHED_PROCESS | subprocess.CREATE_NEW_PROCESS_GROUP,
            )
        else:
            subprocess.Popen(
                [chrome_exe, "--remote-debugging-port=9222",
                 f"--user-data-dir={temp_dir}", "https://www.tiktok.com/"],
                stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                start_new_session=True,
            )
    except Exception as e:
        logger.error(f"Failed to launch Chrome: {e}")
        return False

    for _ in range(15):
        await asyncio.sleep(1)
        port = await _find_chrome_debug_port()
        if port:
            logger.info(f"Chrome debug mode started on port {port}")
            return True
    return False


# ── Main entry point ───────────────────────────────────

async def auto_extract_cookies(force_refresh: bool = False) -> tuple[bool, str]:
    """Extract TikTok cookies via Chrome DevTools Protocol.

    Returns:
        (success: bool, message: str)
    """
    domains = ["https://www.tiktok.com", "https://tiktok.com"]
    output_path = str(COOKIES_FILE)

    # Check cache
    if not force_refresh and os.path.exists(output_path):
        if os.path.getsize(output_path) > 100:
            age = time.time() - os.path.getmtime(output_path)
            if age < COOKIE_TTL_SECONDS:
                return True, f"Cookie cache valid ({(age / 3600):.1f}h ago)"

    # Find Chrome debug port
    port = await _find_chrome_debug_port()
    if not port:
        logger.info("No Chrome debug port found, trying to launch...")
        launched = await _launch_chrome_with_debug()
        if not launched:
            return False, (
                "Chrome debug port not found. Please:\n"
                "1. Close all Chrome windows\n"
                "2. Run: chrome.exe --remote-debugging-port=9222\n"
                "3. Log in to tiktok.com in Chrome\n"
                "4. Try again"
            )
        port = await _find_chrome_debug_port()
        if not port:
            return False, "Chrome launched but debug port still unavailable"

    # Get cookies via CDP
    try:
        cookies = await _cdp_get_cookies(port, domains)
    except RuntimeError as e:
        return False, str(e)

    tik_cookies = [
        c for c in cookies
        if (c.get("domain", "") or "").lower() in (
            "tiktok.com", ".tiktok.com", "www.tiktok.com",
        ) or (c.get("domain", "") or "").lower().endswith(".tiktok.com")
    ]

    if not tik_cookies:
        return False, (
            "No TikTok cookies found in Chrome.\n"
            "Please visit tiktok.com and log in first."
        )

    # Save to cookies.txt
    netscape = _cookies_to_netscape(tik_cookies)
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)
    Path(output_path).write_text(netscape, encoding="utf-8")

    logger.info(f"Extracted {len(tik_cookies)} TikTok cookies via CDP (port {port})")
    return True, f"Extracted {len(tik_cookies)} TikTok cookies"
